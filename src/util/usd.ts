/**
 * 美元金额的**唯一显示口径**（4 位小数）。
 *
 * 为什么值得一个模块：这个数字出现在三处语义不同的地方 —— 回归门的 reason
 * （`$0.0100 → $0.0200`）、预算理由（`已花 $… ≥ 上限 $…`）、CLI 回执。此前各写
 * `${n.toFixed(4)}`，共 13 处 / 3 个文件：改一次精度（换 6 位、加千分位、改成「$0.01」）
 * 要改 13 个地方，漏一处就是「同一份报告两种精度」，而**没有任何测试会红**。
 *
 * 只格式化、**不判断** `costKnown`：「成本未知」是语义，不是显示细节 —— 那个判断必须留在
 * 知道答案的调用点（把「未知」当 0 印出来是这套系统最不该犯的错，见 cost.ts 头注）。
 */
export function usd(n: number): string {
  return `$${n.toFixed(4)}`;
}
